// Non-destructive schema definition for the stickers database.
//
//   npm run db:schema:dump [-- --database=NAME]   write db/schema.sql from a database
//   npm run db:schema:load -- --database=NAME     create missing tables in a database
//
// The dump uses CREATE TABLE IF NOT EXISTS (no DROP statements) and records the
// applied migration versions with INSERT IGNORE, so loading it never removes
// or overwrites existing tables or data.
import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import type { RowDataPacket } from "mysql2/promise";
import { fail, loadDb, parseArgs } from "./db-cli.ts";

const SCHEMA_FILE = path.resolve(import.meta.dirname, "../db/schema.sql");
// Rails-internal bookkeeping; not used by the Node app.
const SKIPPED_TABLES = new Set(["ar_internal_metadata"]);

async function dump(db: Awaited<ReturnType<typeof loadDb>>, database: string) {
  const tables = (await db.query<RowDataPacket>("SHOW FULL TABLES WHERE Table_type = 'BASE TABLE'"))
    .map((row) => String(Object.values(row)[0]))
    .filter((table) => !SKIPPED_TABLES.has(table))
    .sort();

  const statements: string[] = [];
  for (const table of tables) {
    const [row] = await db.query<RowDataPacket>(`SHOW CREATE TABLE \`${table}\``);
    const ddl = String(row["Create Table"])
      .replace(/^CREATE TABLE /, "CREATE TABLE IF NOT EXISTS ")
      .replace(/ AUTO_INCREMENT=\d+/, "");
    statements.push(`${ddl};`);
  }

  const versions = (await db.query<RowDataPacket>("SELECT version FROM schema_migrations ORDER BY version")).map(
    (row) => String(row.version),
  );
  const versionRows = versions.map((version) => `  ('${version}')`).join(",\n");

  const header = [
    "-- Stickers database schema. Generated by `npm run db:schema:dump`; do not edit by hand.",
    `-- Source database: ${database}. Safe to load into an existing database (no DROP statements).`,
    "",
  ].join("\n");
  const body = `${statements.join("\n\n")}\n\nINSERT IGNORE INTO \`schema_migrations\` (\`version\`) VALUES\n${versionRows};\n`;
  await writeFile(SCHEMA_FILE, `${header}\n${body}`);
  console.log(`wrote ${path.relative(process.cwd(), SCHEMA_FILE)}: ${tables.length} tables, ${versions.length} migration versions`);
}

async function load(db: Awaited<ReturnType<typeof loadDb>>, database: string) {
  const sql = (await readFile(SCHEMA_FILE, "utf8")).replace(/^--.*$/gm, "");
  const statements = sql.split(/;\s*(?:\r?\n|$)/).map((s) => s.trim()).filter(Boolean);
  for (const statement of statements) await db.execute(statement);
  console.log(`loaded ${statements.length} statements into ${database}`);
}

async function main() {
  const command = process.argv[2];
  if (command !== "dump" && command !== "load") throw new Error("Usage: db-schema.ts <dump|load> [--database=NAME]");

  const db = await loadDb(parseArgs(process.argv.slice(3)));
  const database = process.env.MYSQL_DATABASE as string;
  try {
    if (command === "dump") await dump(db, database);
    else await load(db, database);
  } finally {
    await db.closePools();
  }
}

main().catch(fail);
